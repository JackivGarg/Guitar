import type { Lesson } from "./course";
import { getChord } from "./course";
type Step = Lesson["steps"][number];
const s = (
  title: string,
  text: string,
  action: string,
  demo = "anatomy",
  chord?: string,
  sourceStart?: number,
): Step => ({ title, text, action, demo, chord, sourceStart });
export function shapeStep(name: string, start?: number): Step {
  const c = getChord(name),
    strings = ["low E", "A", "D", "G", "B", "high e"];
  const fingers = ["", "index", "middle", "ring", "little"];
  const placements = c.frets
    .map((f, i) =>
      f > 0
        ? `${fingers[c.fingers[i]]} finger (${c.fingers[i]}) on ${strings[i]}${f}`
        : null,
    )
    .filter(Boolean)
    .join("; ");
  return s(
    `Build ${name}, then check every string`,
    `${c.tip}\n\nUse the diagram as a front view: thick low E on the left, thin high e on the right. Your finger map is: ${placements}. O means open; × means omit that string. ${c.barre ? "The horizontal finger bar covers several strings. Build it in short attempts; release your hand fully between attempts." : "Curve the fingertips so they do not touch neighboring strings."}\n\nPlace the shape without strumming first. Then pluck each intended string once. Fix the individual dull or buzzing string before trying a full strum.`,
    `Make ${name} five times. After each placement, pluck the intended strings one by one, strum once, then release your hand. Aim for three clean placements.`,
    "chord",
    name,
    start,
  );
}
